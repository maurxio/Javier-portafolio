const year = document.getElementById("year");
const themeToggle = document.querySelector(".theme-toggle");
const languageButtons = document.querySelectorAll(".language-button");
const pageSkeleton = document.querySelector(".page-skeleton");

document.body.classList.add("is-loading");
window.addEventListener("load", () => {
  window.setTimeout(() => {
    pageSkeleton.classList.add("is-hidden");
    document.body.classList.remove("is-loading");
  }, 450);
});

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  const isDark = theme === "dark";
  themeToggle.setAttribute("aria-pressed", String(isDark));
  themeToggle.setAttribute("aria-label", isDark ? "Activar modo claro" : "Activar modo oscuro");
  themeToggle.querySelector(".theme-label").textContent = isDark ? "Claro" : "Modo";
  localStorage.setItem("theme", theme);
}

function setLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;
  document.title = language === "en" ? "Javier Ortiz — Software developer" : "Javier Ortiz — Desarrollador de software";
  document.querySelector('meta[name="description"]').content = language === "en"
    ? "Javier Mauricio Ortiz Millán — Junior software developer in Cali focused on web development, automation, and systems integration."
    : "Javier Mauricio Ortiz Millán — Desarrollador de software junior en Cali, especializado en desarrollo web, automatización e integración de sistemas.";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  languageButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === language);
  });
  localStorage.setItem("language", language);
}

year.textContent = new Date().getFullYear();
themeToggle.addEventListener("click", () => {
  setTheme(document.documentElement.dataset.theme === "dark" ? "light" : "dark");
});
languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

setTheme(localStorage.getItem("theme") || "light");
setLanguage(localStorage.getItem("language") || "es");
